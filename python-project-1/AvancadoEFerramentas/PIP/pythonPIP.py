# --- ENTENDENDO O PIP E PACOTES ---

# PIP: É o "Instalador de Pacotes" do Python. Ele automatiza o 
# processo de baixar, instalar e atualizar bibliotecas.

# PACOTE: É um conjunto de arquivos que formam um módulo ou um 
# conjunto de módulos. Pense nele como uma "caixa" de ferramentas 
# pronta para uso.

# BIBLIOTECA (Library): É o nome comum que damos aos pacotes que 
# adicionam novas funcionalidades ao seu código (ex: Pandas para 
# dados, Flask para web).